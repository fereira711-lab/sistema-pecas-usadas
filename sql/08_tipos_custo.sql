-- Preserva flexibilidade: tipos antigos que ja existem nos custos tambem entram no cadastro.
insert into public.tipos_custo (nome, categoria)
select distinct custos_antigos.nome, custos_antigos.categoria
from (
  select
    case
      when lower(trim(tipo_custo)) in ('comissao', 'comissão') then 'Comissão'
      when lower(trim(tipo_custo)) in ('outro', 'outros') then 'Outros'
      else upper(left(trim(tipo_custo), 1)) || lower(substr(trim(tipo_custo), 2))
    end as nome,
    categoria
  from (
    select tipo_custo, 'peca' as categoria from public.custos_peca
    union all
    select tipo_custo, 'venda' as categoria from public.custos_venda
  ) custos
  where tipo_custo is not null
    and trim(tipo_custo) <> ''
) custos_antigos
where not exists (
  select 1
  from public.tipos_custo existente
  where lower(trim(existente.nome)) = lower(trim(custos_antigos.nome))
);
alter table public.custos_peca
add column if not exists tipo_custo_id bigint references public.tipos_custo(id);

alter table public.custos_peca
add column if not exists observacoes text;

alter table public.custos_venda
add column if not exists tipo_custo_id bigint references public.tipos_custo(id);

alter table public.custos_venda
add column if not exists observacoes text;

update public.custos_peca custo
set tipo_custo_id = tipo.id
from public.tipos_custo tipo
where custo.tipo_custo_id is null
  and lower(trim(
    case
      when lower(trim(custo.tipo_custo)) in ('comissao', 'comissão') then 'Comissão'
      when lower(trim(custo.tipo_custo)) in ('outro', 'outros') then 'Outros'
      else custo.tipo_custo
    end
  )) = lower(trim(tipo.nome));

update public.custos_venda custo
set tipo_custo_id = tipo.id
from public.tipos_custo tipo
where custo.tipo_custo_id is null
  and lower(trim(
    case
      when lower(trim(custo.tipo_custo)) in ('comissao', 'comissão') then 'Comissão'
      when lower(trim(custo.tipo_custo)) in ('outro', 'outros') then 'Outros'
      else custo.tipo_custo
    end
  )) = lower(trim(tipo.nome));
