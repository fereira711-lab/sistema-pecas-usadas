-- Cadastro controlado de tipos de custo.
-- Mantem as colunas texto antigas para nao quebrar custos ja cadastrados.

create table if not exists public.tipos_custo (
  id bigint generated by default as identity primary key,
  nome text not null,
  categoria text not null default 'ambos',
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  constraint tipos_custo_categoria_check check (categoria in ('peca', 'venda', 'ambos'))
);

alter table public.tipos_custo
add column if not exists categoria text not null default 'ambos';

alter table public.tipos_custo
drop constraint if exists tipos_custo_categoria_check;

alter table public.tipos_custo
add constraint tipos_custo_categoria_check check (categoria in ('peca', 'venda', 'ambos'));

create unique index if not exists tipos_custo_nome_unico_idx
on public.tipos_custo (lower(trim(nome)));

insert into public.tipos_custo (nome, categoria)
select tipo.nome, tipo.categoria
from (
  values
    ('Limpeza', 'peca'),
    ('Solda', 'peca'),
    ('Pintura', 'peca'),
    ('Conserto', 'peca'),
    ('Preparo', 'peca'),
    ('Embalagem', 'venda'),
    ('Frete', 'venda'),
    ('Comissão', 'venda'),
    ('Taxa marketplace', 'venda'),
    ('Taxa cartão', 'venda'),
    ('Coleta', 'venda'),
    ('Etiqueta', 'venda'),
    ('Outros', 'venda')
) as tipo(nome, categoria)
where not exists (
  select 1
  from public.tipos_custo existente
  where lower(trim(existente.nome)) = lower(trim(tipo.nome))
);

update public.tipos_custo existente
set categoria = tipo.categoria
from (
